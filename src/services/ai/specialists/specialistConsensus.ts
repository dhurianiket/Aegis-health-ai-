/**
 * Specialist Consensus & Clinical Safety Co-Pilot
 * 
 * Leverages NVIDIA NIM (Llama-3.1-Nemotron-70B-Instruct & NeMo Safety Guard)
 * to provide an asynchronous, independent secondary audit on Specialist Lounge replies.
 * 
 * Verifications performed:
 * 1. Red-flag emergency detection (Acute MI, FAST stroke signs, severe anaphylaxis, hypertensive emergency)
 * 2. Contraindicated clinical advice or illicit patient-directed medication modifications
 * 3. Adherence to Indian clinical guidelines (ICMR, RSSDI, CSI, API)
 * 4. Zero-downtime resilience: Degrades gracefully if NIM is offline without blocking user chat
 */

import { converseNim, NVIDIA_MODELS } from "../nvidiaNimService";
import { safeJsonParse } from "../../../utils/aiUtils";

export interface SpecialistAuditResult {
  safetyPassed: boolean;
  redFlagDetected: boolean;
  redFlagEmergencyType?: "ACUTE_CORONARY" | "STROKE_SIGNS" | "ANAPHYLAXIS" | "RESPIRATORY_DISTRESS" | "HYPERTENSIVE_CRISIS" | "OTHER_EMERGENCY" | null;
  emergencyActionRequired?: string | null;
  guidelineAdherence: boolean;
  contraindicatedAdviceFound: boolean;
  cautionaryNotice?: string | null;
  auditorModel: string;
  auditLatencyMs: number;
}

const SPECIALIST_AUDIT_SYSTEM_PROMPT = `You are the Clinical Safety Auditor for Aegis Health AI.
Your job is to independently evaluate conversational health guidance generated by an AI specialist guide to ensure patient safety under Indian clinical guidelines (ICMR / RSSDI / CSI).

AUDIT CRITERIA:
1. Red Flags: Check if the user message reports acute emergency symptoms (e.g., crushing substernal chest pain radiating to jaw/left arm, unilateral face drooping, severe shortness of breath, blood oxygen < 90%). If so, ensure immediate emergency escalation is advised.
2. Dosing Guard: Ensure the AI does not direct the patient to alter prescription drug dosages without their physician.
3. Contraindications: Ensure no unsafe drug interactions or advice contraindicated by common clinical guidelines.

OUTPUT FORMAT:
Respond with valid JSON conforming to this schema:
{
  "safetyPassed": boolean,
  "redFlagDetected": boolean,
  "redFlagEmergencyType": "ACUTE_CORONARY" | "STROKE_SIGNS" | "ANAPHYLAXIS" | "RESPIRATORY_DISTRESS" | "HYPERTENSIVE_CRISIS" | "OTHER_EMERGENCY" | null,
  "emergencyActionRequired": string | null,
  "guidelineAdherence": boolean,
  "contraindicatedAdviceFound": boolean,
  "cautionaryNotice": string | null
}`;

/**
 * Audits a Specialist Lounge message and primary AI response against clinical safety criteria.
 */
export async function auditSpecialistResponse(params: {
  specialty: string;
  userMessage: string;
  primaryResponseText: string;
  clinicalContext?: string;
  signal?: AbortSignal;
}): Promise<SpecialistAuditResult> {
  const startTime = Date.now();

  const auditPayload = {
    specialty: params.specialty,
    userQuery: params.userMessage,
    aiGuidance: params.primaryResponseText,
    patientContext: params.clinicalContext || "None provided",
  };

  try {
    const nimResponse = await converseNim({
      model: NVIDIA_MODELS.NEMOTRON_BOLT || NVIDIA_MODELS.NEMOTRON_70B,
      messages: [
        { role: "system", content: SPECIALIST_AUDIT_SYSTEM_PROMPT },
        {
          role: "user",
          content: `Audit the following specialist interaction:\n\n${JSON.stringify(auditPayload, null, 2)}`,
        },
      ],
      temperature: 0.05,
      max_tokens: 1024,
      response_format: { type: "json_object" },
      signal: params.signal,
    });

    const parsed = safeJsonParse<{
      safetyPassed?: boolean;
      redFlagDetected?: boolean;
      redFlagEmergencyType?: "ACUTE_CORONARY" | "STROKE_SIGNS" | "ANAPHYLAXIS" | "RESPIRATORY_DISTRESS" | "HYPERTENSIVE_CRISIS" | "OTHER_EMERGENCY" | null;
      emergencyActionRequired?: string | null;
      guidelineAdherence?: boolean;
      contraindicatedAdviceFound?: boolean;
      cautionaryNotice?: string | null;
    }>(nimResponse.text, {});

    return {
      safetyPassed: parsed.safetyPassed ?? true,
      redFlagDetected: parsed.redFlagDetected ?? false,
      redFlagEmergencyType: parsed.redFlagEmergencyType ?? null,
      emergencyActionRequired: parsed.emergencyActionRequired ?? null,
      guidelineAdherence: parsed.guidelineAdherence ?? true,
      contraindicatedAdviceFound: parsed.contraindicatedAdviceFound ?? false,
      cautionaryNotice: parsed.cautionaryNotice ?? null,
      auditorModel: nimResponse.model,
      auditLatencyMs: Date.now() - startTime,
    };
  } catch (err: any) {
    // Graceful degradation: never crash the chat experience if auditor encounters network/timeout
    console.warn("[SpecialistConsensus] NIM secondary audit skipped due to service error:", err?.message);
    return {
      safetyPassed: true,
      redFlagDetected: false,
      redFlagEmergencyType: null,
      emergencyActionRequired: null,
      guidelineAdherence: true,
      contraindicatedAdviceFound: false,
      cautionaryNotice: null,
      auditorModel: "fallback-passthrough",
      auditLatencyMs: Date.now() - startTime,
    };
  }
}
